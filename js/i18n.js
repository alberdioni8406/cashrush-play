let current = 'en';

function detectLocale() {
  try {
    const saved = Storage.get('language');
    if (saved && STRINGS[saved]) return saved;
  } catch (_) {}
  try {
    const nav = (navigator.language || navigator.userLanguage || 'en').toLowerCase();
    const short = nav.slice(0, 2);
    if (STRINGS[short]) return short;
    if (nav.startsWith('zh')) return 'zh';
    if (nav.startsWith('pt')) return 'pt';
  } catch (_) {}
  return 'en';
}

export const I18n = {
  LOCALES,

  init() {
    current = detectLocale();
    document.documentElement.lang = current;
    const meta = LOCALES.find(l => l.code === current);
    document.documentElement.dir = meta?.dir || 'ltr';
    return current;
  },

  getLocale() {
    return current;
  },

  setLocale(code) {
    if (!STRINGS[code]) code = 'en';
    current = code;
    try {
      Storage.set('language', code);
    } catch (_) {}
    document.documentElement.lang = code;
    const meta = LOCALES.find(l => l.code === code);
    document.documentElement.dir = meta?.dir || 'ltr';
    this.applyDOM();
    return current;
  },

  t(key, fallback) {
    const pack = STRINGS[current] || STRINGS.en;
    if (pack[key] != null) return pack[key];
    if (STRINGS.en[key] != null) return STRINGS.en[key];
    return fallback != null ? fallback : key;
  },

  /** Localized achievement fields */
  ach(id, field, englishFallback) {
    const pack = ACH_I18N[current];
    if (pack && pack[id] && pack[id][field] != null) return pack[id][field];
    return englishFallback;
  },

  applyDOM() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const val = this.t(key);
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') return;
      el.textContent = val;
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      el.setAttribute('placeholder', this.t(el.getAttribute('data-i18n-placeholder')));
    });
  }
};

export function t(key, fallback) {
  return I18n.t(key, fallback);
}
